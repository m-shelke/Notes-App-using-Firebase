package com.example.notesappusingfirebase.Model;

public class RequestStatusModel {

    private String userId;     // ID of the person who receives the request
    private String name;
    private String email;
    private String profile;
    private String status;     // "pending", "accepted", "rejected"
    private String timestamp;    // when request was sent
    private String actionTime;   // when request was accepted/rejected

    public RequestStatusModel() {
        // required empty constructor
    }

    public String getUserId() {
        return userId;
    }

    public void setUserId(String userId) {
        this.userId = userId;
    }

    public String getName() {
        return name;
    }

    public void setName(String name) {
        this.name = name;
    }

    public String getEmail() {
        return email;
    }

    public void setEmail(String email) {
        this.email = email;
    }

    public String getProfile() {
        return profile;
    }

    public void setProfile(String profile) {
        this.profile = profile;
    }

    public String getStatus() {
        return status;
    }

    public void setStatus(String status) {
        this.status = status;
    }

    public String getTimestamp() {
        return timestamp;
    }

    public void setTimestamp(String timestamp) {
        this.timestamp = timestamp;
    }

    public String getActionTime() {
        return actionTime;
    }

    public void setActionTime(String actionTime) {
        this.actionTime = actionTime;
    }
}

